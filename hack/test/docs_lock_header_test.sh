#!/usr/bin/env bash
# The docs Python lock's compile header is in the form Renovate's pip-compile manager can parse.
#
# Renovate (pip-compile manager, renovate.json `pip-compile.managerFilePatterns`) reads the
# command line from a uv / pip-compile lock header and replays it to regenerate the lock. Its
# parser rejects any option that takes a value when the value is a separate token
# (`--python-version 3.12`): extraction fails with "Option --python-version must have equal sign
# '=' separating it's argument", the manager extracts no dependency, and the run stays green with
# only a WARN line. That hid the docs lock from Renovate on every run until 2026-10-19.
#
# What it locks, for every git-tracked docs/**/*.txt whose first line is the uv or pip-compile
# "autogenerated by" banner:
#   * the header has a command line: the first `#` + four spaces line inside the leading comment
#     block (the line Renovate's constraintLineRegex takes);
#   * no token of that line is a bare option that takes a value (OPTIONS_WITH_VALUE below, copied
#     from Renovate 44.167.7 lib/modules/manager/pip-compile/common.ts optionsWithArguments):
#     each must be written `--opt=value`; every offender is named;
#   * the scan is never vacuous: no such lock under docs/ (or a root that is not the top of a git
#     work tree) fails instead of passing.
# Untracked files are not seen (Renovate reads what is committed).
#
# Regenerate the lock with the `=` form (uv writes the header from the argv it was given):
#   uv pip compile --python-version=3.12 --generate-hashes \
#     --output-file=docs/requirements-docs.txt docs/requirements-docs.in
#
# Usage:
#   hack/test/docs_lock_header_test.sh              # check the repository tree
#   hack/test/docs_lock_header_test.sh --self-test  # mutate copies, assert each check fails
#   hack/test/docs_lock_header_test.sh <tree-root>  # check an arbitrary git work tree
set -euo pipefail

fail() {
  echo "FAIL: $*" >&2
  exit 1
}

pass() {
  echo "ok - $*"
}

SELF="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/$(basename "${BASH_SOURCE[0]}")"

MODE="check"
if [[ "${1:-}" == "--self-test" ]]; then
  MODE="self-test"
  shift
fi

ROOT="${1:-}"
if [[ -z "${ROOT}" ]]; then
  ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
fi
ROOT="$(cd "${ROOT}" && pwd -P)"

command -v git >/dev/null 2>&1 || fail "git not found; install it to run this test"

LOCK_GLOB=':(glob)docs/**/*.txt'
BANNER_RE='^# This file (was|is) autogenerated by (uv|pip-compile)'
OPTIONS_WITH_VALUE=(
  --output-file --extra --extra-index-url --resolver --constraint --constraints
  --python-version --no-emit-package --prerelease --format --resolution --fork-strategy
  --exclude-newer --exclude-newer-package --group --override --overrides
)

# Prints the header command line of a lock (without the leading "#    "), or nothing.
header_command() {
  awk '
    !/^#/ { exit }
    /^# {4}[^ ]/ { sub(/^# {4}/, ""); print; exit }
  ' "$1"
}

check_locks() {
  local root="$1" top
  top="$(git -C "${root}" rev-parse --show-toplevel 2>/dev/null)" || {
    echo "FAIL: ${root} is not a git work tree; nothing was scanned" >&2
    return 1
  }
  top="$(cd "${top}" && pwd -P)"
  if [[ "${top}" != "${root}" ]]; then
    echo "FAIL: ${root} is not the top of its git work tree (${top}); nothing was scanned" >&2
    return 1
  fi
  local -a files=()
  mapfile -d '' -t files < <(git -C "${root}" ls-files -z -- "${LOCK_GLOB}")
  local f cmd tok opt locks=0 bad=0
  for f in "${files[@]}"; do
    [[ -f "${root}/${f}" ]] || continue
    head -n 1 "${root}/${f}" | grep -Eq "${BANNER_RE}" || continue
    locks=$((locks + 1))
    cmd="$(header_command "${root}/${f}")"
    if [[ -z "${cmd}" ]]; then
      echo "FAIL: ${f} has no compile command line in its header (a '#    <command>' line in the leading comment block)" >&2
      bad=$((bad + 1))
      continue
    fi
    local -a toks=()
    read -r -a toks <<<"${cmd}"
    for tok in "${toks[@]}"; do
      for opt in "${OPTIONS_WITH_VALUE[@]}"; do
        if [[ "${tok}" == "${opt}" ]]; then
          echo "FAIL: ${f}: header option ${opt} takes a value but is not written '${opt}=<value>' (Renovate's pip-compile manager rejects the file)" >&2
          bad=$((bad + 1))
        fi
      done
    done
  done
  if [[ "${locks}" -eq 0 ]]; then
    echo "FAIL: no tracked uv/pip-compile lock under docs/; the scan read nothing" >&2
    return 1
  fi
  [[ "${bad}" -eq 0 ]] || return 1
  echo "ok - ${locks} docs lock header(s), every option with a value in '=' form"
}

if [[ "${MODE}" == "check" ]]; then
  if check_locks "${ROOT}"; then
    pass "docs lock headers are parseable by Renovate's pip-compile manager"
    exit 0
  fi
  fail "a docs lock header is not in Renovate's '--opt=value' form, or there is nothing to scan (listed above)"
fi

# ---------------------------------------------------------------------------
# Self-test (CFC-6 shape): copy the tracked docs/**/*.txt files into a fresh git work tree, break
# one invariant per copy, and assert the gate reds WITH THE MESSAGE of the clause the mutant
# targets -- a non-zero exit alone is not evidence. Unmutated and in-scope-but-valid copies pass.
# Mutant values are derived from the real header, never copied into this file.
# ---------------------------------------------------------------------------
COPY=""
cleanup() { [[ -n "${COPY}" ]] && rm -rf "${COPY}" 2>/dev/null; return 0; }
trap cleanup EXIT

# Called directly (never as $(new_copy)), so COPY survives in this shell. Frees the previous copy.
new_copy() {
  cleanup
  COPY="$(mktemp -d)"
  git -C "${COPY}" init -q
  git -C "${ROOT}" ls-files -z -- "${LOCK_GLOB}" | tar -C "${ROOT}" --null -T - -cf - | tar -C "${COPY}" -xf - ||
    fail "self-test: copying the tracked docs/**/*.txt files failed -- nothing was tested"
  git -C "${COPY}" add -A -f
}

# The real lock the mutants start from: the first tracked docs lock with the banner.
LOCK=""
while IFS= read -r -d '' f; do
  if head -n 1 "${ROOT}/${f}" | grep -Eq "${BANNER_RE}"; then
    LOCK="${f}"
    break
  fi
done < <(git -C "${ROOT}" ls-files -z -- "${LOCK_GLOB}")
[[ -n "${LOCK}" ]] || fail "self-test: no tracked uv/pip-compile lock under docs/ to mutate -- run the plain mode first"
REAL_CMD="$(header_command "${ROOT}/${LOCK}")"
[[ "${REAL_CMD}" == *"--python-version="* && "${REAL_CMD}" == *"--output-file="* ]] ||
  fail "self-test: ${LOCK}'s header has no --python-version=/--output-file= to mutate; fix the real tree first (got: ${REAL_CMD})"

# set_cmd <file> <new command>: replace the header command line of a copy's lock.
set_cmd() {
  local file="$1" new="$2"
  NEW="${new}" awk '
    !done && /^# {4}[^ ]/ { print "#    " ENVIRON["NEW"]; done = 1; next }
    { print }
  ' "${COPY}/${file}" >"${COPY}/${file}.tmp" && mv "${COPY}/${file}.tmp" "${COPY}/${file}"
  git -C "${COPY}" add -A -f
}

# expect_red <label> <sentinel>: the gate on the current copy reds with the sentinel.
expect_red() {
  local label="$1" sentinel="$2" out rc
  out="$(bash "${SELF}" "${COPY}" 2>&1)" && rc=0 || rc=$?
  [[ "${rc}" -ne 0 ]] ||
    fail "self-test: the gate accepted the '${label}' mutant (exit 0) -- the assertion '${sentinel}' did not fire"
  grep -Fq -- "${sentinel}" <<<"${out}" ||
    fail "self-test: the '${label}' mutant red for the WRONG reason; expected '${sentinel}', got: $(grep FAIL <<<"${out}" | head -3 | tr '\n' ' ')"
  pass "self-test: ${label} rejected with '${sentinel}'"
}

expect_green() {
  local label="$1" out
  out="$(bash "${SELF}" "${COPY}" 2>&1)" ||
    fail "self-test: the gate red on the '${label}' control -- it must pass: $(grep FAIL <<<"${out}" | head -2 | tr '\n' ' ')"
  pass "self-test: ${label} control passes"
}

# landed <file> <text>: the mutation is in the copy's header (what the gate reads).
landed() {
  [[ "$(header_command "${COPY}/$1")" == *"$2"* ]] ||
    fail "self-test: the mutant did not land ('$2' not in ${COPY}/$1's header) -- nothing was tested"
}

new_copy
expect_green "no-op (unmutated copy)"

# Clause: an option with a value in space form. Each value is the real one, only the '=' becomes
# a space (the 2026-10-19 shape).
for opt in --python-version --output-file; do
  new_copy
  spaced="${REAL_CMD/${opt}=/${opt} }"
  set_cmd "${LOCK}" "${spaced}"
  landed "${LOCK}" "${opt} "
  expect_red "${opt} in space form" "FAIL: ${LOCK}: header option ${opt} takes a value"
done

# An option the real header does not use today (uv adds it the day someone passes it).
new_copy
set_cmd "${LOCK}" "${REAL_CMD} --extra-index-url https://example.invalid/simple"
landed "${LOCK}" "--extra-index-url https"
expect_red "added --extra-index-url in space form" "FAIL: ${LOCK}: header option --extra-index-url takes a value"

# Every offender is named, not only the first, across files: the real lock (sorted first) also
# offends, so naming the second proves the scan does not stop at the first offender.
new_copy
second="docs/zz-selftest-lock.txt"
cp "${COPY}/${LOCK}" "${COPY}/${second}"
set_cmd "${LOCK}" "${REAL_CMD/--python-version=/--python-version }"
landed "${LOCK}" "--python-version "
set_cmd "${second}" "${REAL_CMD/--output-file=/--output-file }"
landed "${second}" "--output-file "
expect_red "second lock also named" "FAIL: ${second}: header option --output-file takes a value"

# Clause: the header has a command line (banner kept, command line removed).
new_copy
awk '!/^# {4}[^ ]/' "${COPY}/${LOCK}" >"${COPY}/${LOCK}.tmp" && mv "${COPY}/${LOCK}.tmp" "${COPY}/${LOCK}"
git -C "${COPY}" add -A -f
[[ -z "$(header_command "${COPY}/${LOCK}")" ]] || fail "self-test: the no-command mutant did not land -- nothing was tested"
expect_red "header without a command line" "FAIL: ${LOCK} has no compile command line"

# Clause: never vacuous. The lock deleted (absence probe: nothing tracked under its path).
new_copy
git -C "${COPY}" rm -q -f -- "${LOCK}"
[[ -z "$(git -C "${COPY}" ls-files -- "${LOCK}")" ]] || fail "self-test: the lock-deleted mutant did not land -- nothing was tested"
expect_red "lock deleted" "FAIL: no tracked uv/pip-compile lock under docs/"

# The root must be the top of its own work tree.
new_copy
mkdir -p "${COPY}/docs"
out="$(bash "${SELF}" "${COPY}/docs" 2>&1)" && rc=0 || rc=$?
[[ "${rc}" -ne 0 ]] && grep -Fq "is not the top of its git work tree" <<<"${out}" ||
  fail "self-test: a root below the work-tree top was not rejected for that reason: ${out}"
pass "self-test: root below the work-tree top rejected"

# Controls. Simulated bot bump: every value in the header changes consistently (a newer Python),
# and the pins move -- the '=' form stays green whatever the values.
new_copy
set_cmd "${LOCK}" "$(sed -E 's/--python-version=[^ ]+/--python-version=99.0/' <<<"${REAL_CMD}")"
landed "${LOCK}" "--python-version=99.0"
sed -i -E 's/^([A-Za-z0-9_.-]+(\[[^]]*\])?)==[^ ]+/\1==99.0.0/' "${COPY}/${LOCK}"
git -C "${COPY}" add -A -f
expect_green "bot bump (python version and every pin)"

# Decoys: valueless flags Renovate allows, and an option name inside a value, are not offenders.
new_copy
set_cmd "${LOCK}" "${REAL_CMD} --universal --no-emit-package=--extra --extra=imaging"
landed "${LOCK}" "--no-emit-package=--extra"
expect_green "valueless flags and '=' values"

# A .txt under docs/ without the lock banner is out of scope, even with a space-form option.
new_copy
printf '# notes\n#    uv pip compile --python-version 3.12\n' >"${COPY}/docs/zz-selftest-notes.txt"
git -C "${COPY}" add -A -f
expect_green "non-lock .txt under docs/"

cleanup
echo "All docs lock header self-tests passed."
